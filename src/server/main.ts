import { GameServer, type GameFeatures } from "./index";

/* THAT INFORMATION COME SOMEWHERE FORM THE GAME OPTIONS */
const HELL_DURATION = 10;
const HEAVEN_DURATION = 10;
const ROUNDS = 3;
const POWER_UPS = true;
const GAME_DURATION = (HELL_DURATION * ROUNDS) + (HEAVEN_DURATION * (ROUNDS + 1));
const BOT_LEVEL = 10;

new GameServer({
    HELL_DURATION: HEAVEN_DURATION,
    HEAVEN_DURATION: HEAVEN_DURATION,
    ROUNDS: ROUNDS,
    POWER_UPS: POWER_UPS,
    GAME_DURATION: GAME_DURATION,
    BOT_LEVEL: BOT_LEVEL
} as GameFeatures);